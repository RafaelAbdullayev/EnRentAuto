-- Дробная ставка за километр сверх лимита пробега.
--
-- Колонка переименована и переведена в МИНОРНЫЕ единицы (гяпики), чтобы
-- ставку 0,30 ₼/км можно было хранить целым числом (30) — без float
-- в денежных расчётах.
--
-- Существующие значения были в целых манатах, поэтому умножаем на 100:
--   1 ₼/км  →  100 гяпиков/км
ALTER TABLE "Car" RENAME COLUMN "overMileageFee" TO "overMileageFeeMinor";

UPDATE "Car" SET "overMileageFeeMinor" = "overMileageFeeMinor" * 100;
